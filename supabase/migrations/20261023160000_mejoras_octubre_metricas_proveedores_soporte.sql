-- 1. Sincronizar consecutivo_actual de tipos_producto con los productos reales
do $$
declare
  r record;
  v_max_num int;
begin
  for r in select id, prefijo from public.tipos_producto loop
    select coalesce(max(nullif(regexp_replace(codigo, '^' || r.prefijo || '-0*', ''), '')::int), 0)
    into v_max_num
    from public.productos
    where codigo like (r.prefijo || '-%');

    update public.tipos_producto
    set consecutivo_actual = greatest(coalesce(consecutivo_actual, 0), v_max_num)
    where id = r.id;
  end loop;
end;
$$;

-- Sincronizar secuencia de ID primaria en productos
select setval(
  pg_get_serial_sequence('public.productos', 'id'),
  coalesce((select max(id) from public.productos), 1)
);

-- Sincronizar preventivamente todas las secuencias de tablas en esquema public
do $$
declare
  r record;
  v_max_id bigint;
  v_seq_name text;
begin
  for r in (
    select table_schema, table_name, column_name
    from information_schema.columns
    where table_schema = 'public'
      and (column_default like 'nextval(%' or is_identity = 'YES')
  ) loop
    v_seq_name := pg_get_serial_sequence(r.table_schema || '.' || r.table_name, r.column_name);
    if v_seq_name is not null then
      execute format('select coalesce(max(%I), 0) from %I.%I', r.column_name, r.table_schema, r.table_name) into v_max_id;
      if v_max_id > 0 then
        perform setval(v_seq_name, v_max_id);
      end if;
    end if;
  end loop;
end;
$$;

-- 2. Función generar_codigo_producto robusta, concurrente y a prueba de colisiones
create or replace function public.generar_codigo_producto(p_tipo_producto_id bigint)
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  v_prefijo text;
  v_nuevo_num integer;
  v_codigo_final text;
  v_max_num_existente integer;
begin
  -- Bloquear la fila del tipo de producto para concurrencia
  select upper(trim(prefijo)), consecutivo_actual
  into v_prefijo, v_nuevo_num
  from public.tipos_producto
  where id = p_tipo_producto_id
  for update;

  if v_prefijo is null or v_prefijo = '' then
    v_prefijo := 'PRD';
  end if;

  if v_nuevo_num is null then
    v_nuevo_num := 0;
  end if;

  -- Calcular el máximo número real en productos para este prefijo si es mayor al consecutivo
  select coalesce(max(nullif(regexp_replace(codigo, '^' || v_prefijo || '-0*', ''), '')::int), 0)
  into v_max_num_existente
  from public.productos
  where codigo like (v_prefijo || '-%');

  if v_max_num_existente > v_nuevo_num then
    v_nuevo_num := v_max_num_existente;
  end if;

  -- Incrementar secuencial
  v_nuevo_num := v_nuevo_num + 1;
  v_codigo_final := v_prefijo || '-' || lpad(v_nuevo_num::text, 6, '0');

  -- Bucle de seguridad para garantizar unicidad absoluta
  while exists (select 1 from public.productos where codigo = v_codigo_final) loop
    v_nuevo_num := v_nuevo_num + 1;
    v_codigo_final := v_prefijo || '-' || lpad(v_nuevo_num::text, 6, '0');
  end loop;

  -- Actualizar consecutivo en la tabla tipos_producto
  update public.tipos_producto
  set consecutivo_actual = v_nuevo_num,
      updated_at = now()
  where id = p_tipo_producto_id;

  return v_codigo_final;
end;
$$;

-- 3. Tabla proveedor_direcciones para múltiples direcciones por proveedor
create table if not exists public.proveedor_direcciones (
  id bigint generated by default as identity primary key,
  proveedor_id bigint not null references public.proveedores(id) on delete cascade,
  titulo text not null default 'Principal',
  direccion text not null,
  ciudad text,
  estado text,
  telefono text,
  es_principal boolean not null default false,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Migrar direcciones existentes en proveedores a proveedor_direcciones
insert into public.proveedor_direcciones (proveedor_id, titulo, direccion, es_principal, activo)
select id, 'Sede Principal', direccion, true, true
from public.proveedores
where direccion is not null and trim(direccion) <> ''
and not exists (
  select 1 from public.proveedor_direcciones pd where pd.proveedor_id = public.proveedores.id
);

-- RLS para proveedor_direcciones
