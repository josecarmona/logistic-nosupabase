-- Función y trigger para código de ticket secuencial (TCK-000001)
create or replace function public.trg_auto_codigo_ticket()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_next_num int;
begin
  if new.codigo is null or trim(new.codigo) = '' then
    select coalesce(max(nullif(regexp_replace(codigo, '^TCK-0*', ''), '')::int), 0) + 1
    into v_next_num
    from public.tickets_soporte;

    new.codigo := 'TCK-' || lpad(v_next_num::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_assign_codigo_ticket on public.tickets_soporte;
create trigger trg_assign_codigo_ticket
  before insert on public.tickets_soporte
  for each row
  execute function public.trg_auto_codigo_ticket();

