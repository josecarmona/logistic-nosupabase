-- ==============================================================================
-- Migración: Control de Inventario de Productos y Movimientos de Stock (Kárdex)
-- ==============================================================================

-- 1. Agregar columna stock a productos (si no existe)
alter table public.productos
  add column if not exists stock numeric(12, 2) not null default 0;

comment on column public.productos.stock is 'Existencia o stock físico actual del producto';

-- 2. Crear tabla de movimientos de inventario (Kárdex)
create table if not exists public.inventario_movimientos (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos(id) on delete cascade,
  tipo_movimiento text not null check (tipo_movimiento in ('entrada', 'salida', 'ajuste')),
  cantidad numeric(12, 2) not null,
  stock_anterior numeric(12, 2) not null default 0,
  stock_nuevo numeric(12, 2) not null default 0,
  referencia text,
  motivo text,
  operador_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

comment on table public.inventario_movimientos is 'Registro de movimientos de inventario (entradas manuales, salidas por ventas y ajustes)';

create index if not exists idx_inv_mov_producto on public.inventario_movimientos(producto_id);
create index if not exists idx_inv_mov_tipo on public.inventario_movimientos(tipo_movimiento);
create index if not exists idx_inv_mov_created_at on public.inventario_movimientos(created_at desc);

-- 3. Habilitar RLS en inventario_movimientos
alter table public.inventario_movimientos enable row level security;

-- Política de lectura para usuarios autenticados
create policy "Usuarios autenticados pueden ver movimientos de inventario"
  on public.inventario_movimientos
  for select
  to authenticated
  using (true);

-- Política de inserción para usuarios autenticados
create policy "Usuarios autenticados pueden registrar movimientos de inventario"
  on public.inventario_movimientos
  for insert
  to authenticated
  with check (true);

-- 4. Registrar permisos granulares
insert into public.permisos (codigo, descripcion, tipo)
values
  ('inventario.ver', 'Ver existencias y kárdex de inventario', 'menu'),
  ('inventario.adicionar', 'Adicionar stock al inventario de productos', 'accion'),
  ('inventario.ajustar', 'Ajustar existencia física de stock de productos', 'accion')
on conflict (codigo) do nothing;

-- 5. Asignar los nuevos permisos a roles admin, gerente y operador
insert into public.rol_permisos (rol_id, permiso_id)
select r.id, p.id
from public.roles r
cross join public.permisos p
where r.nombre in ('admin', 'gerente', 'operador')
  and p.codigo in ('inventario.ver', 'inventario.adicionar', 'inventario.ajustar')
on conflict do nothing;
