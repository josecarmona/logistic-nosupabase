-- Migración: Maestro CRUD de Conceptos y Métodos de Pago

create table if not exists public.conceptos_pago (
  id bigint generated by default as identity primary key,
  nombre varchar(100) not null unique,
  requiere_referencia boolean not null default true,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Habilitar RLS
alter table public.conceptos_pago enable row level security;

drop policy if exists "Lectura pública de conceptos_pago para autenticados" on public.conceptos_pago;
create policy "Lectura pública de conceptos_pago para autenticados"
  on public.conceptos_pago for select
  to authenticated
  using (true);

drop policy if exists "Escritura de conceptos_pago para autenticados" on public.conceptos_pago;
create policy "Escritura de conceptos_pago para autenticados"
  on public.conceptos_pago for all
  to authenticated
  using (true);

-- Sembrar conceptos de pago iniciales
insert into public.conceptos_pago (nombre, requiere_referencia, activo) values
  ('EFECTIVO', false, true),
  ('TRANSFERENCIA BANCARIA', true, true),
  ('PAGO MÓVIL', true, true),
  ('PUNTO DE VENTA', true, true),
  ('ZELLE', true, true)
on conflict (nombre) do update set
  requiere_referencia = excluded.requiere_referencia;
