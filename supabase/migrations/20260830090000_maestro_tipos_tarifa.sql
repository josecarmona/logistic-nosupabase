-- Migración: Tabla de Maestro de Tipos de Tarifa

create table if not exists public.tipos_tarifa (
  id bigint generated by default as identity primary key,
  nombre varchar(100) not null unique,
  promocion boolean not null default false,
  numero_productos integer not null default 1 check (numero_productos >= 1),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Habilitar RLS en tipos_tarifa
alter table public.tipos_tarifa enable row level security;

-- Políticas de RLS para tipos_tarifa
drop policy if exists "Lectura pública de tipos de tarifa para autenticados" on public.tipos_tarifa;
create policy "Lectura pública de tipos de tarifa para autenticados"
  on public.tipos_tarifa for select
  to authenticated
  using (true);

drop policy if exists "Escritura de tipos de tarifa para autenticados" on public.tipos_tarifa;
create policy "Escritura de tipos de tarifa para autenticados"
  on public.tipos_tarifa for all
  to authenticated
  using (true);

-- Sembrar tipos de tarifa iniciales
insert into public.tipos_tarifa (nombre, promocion, numero_productos, activo) values
  ('ESTÁNDAR', false, 1, true),
  ('PROMOCIONAL', true, 1, true),
  ('AL POR MAYOR (PACK 5)', false, 5, true)
on conflict (nombre) do update set
  promocion = excluded.promocion,
  numero_productos = excluded.numero_productos;
